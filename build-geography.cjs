const fs = require('node:fs');
const path = require('node:path');
const source = JSON.parse(fs.readFileSync(path.join(__dirname, 'natural-earth-land.geojson'), 'utf8'));
const bounds = { west: -14, east: 37, north: 48, south: 28 };
const width = 1440;
const merc = lat => Math.log(Math.tan(Math.PI / 4 + lat * Math.PI / 360)) * 180 / Math.PI;
const scale = width / (bounds.east - bounds.west);
const height = Math.ceil((merc(bounds.north) - merc(bounds.south)) * scale);
const project = ([lon, lat]) => [(lon - bounds.west) * scale, (merc(bounds.north) - merc(lat)) * scale];
function clip(ring, axis, boundary, sign) {
  const output = [];
  for (let i = 0; i < ring.length; i++) {
    const a = ring[i], b = ring[(i + 1) % ring.length];
    const ain = sign * (a[axis] - boundary) >= 0, bin = sign * (b[axis] - boundary) >= 0;
    if (ain) output.push(a);
    if (ain !== bin) { const t = (boundary - a[axis]) / (b[axis] - a[axis]); output.push([a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t]); }
  }
  return output;
}
const rings = [];
for (const feature of source.features) {
  const polygons = feature.geometry.type === 'Polygon' ? [feature.geometry.coordinates] : feature.geometry.coordinates;
  for (const polygon of polygons) for (const raw of polygon) {
    if (!raw.some(([x, y]) => x >= -30 && x <= 60 && y >= 10 && y <= 70)) continue;
    let ring = raw.slice(0, -1).map(project);
    for (const [axis, border, sign] of [[0, 0, 1], [0, width, -1], [1, 0, 1], [1, height, -1]]) ring = clip(ring, axis, border, sign);
    ring = ring.map(p => p.map(v => Math.round(v * 100) / 100));
    ring = ring.filter((p, i) => !i || p[0] !== ring[i - 1][0] || p[1] !== ring[i - 1][1]);
    if (ring.length >= 3) rings.push(ring);
  }
}
const data = { width, height, bounds, source: 'Natural Earth 1:50m land, public domain', rings };
fs.writeFileSync(path.join(__dirname, 'geography.js'), `// Generated by build-geography.cjs from public-domain Natural Earth data.\n(function(root){const data=${JSON.stringify(data)};if(typeof module!=='undefined')module.exports=data;root.SeaGeography=data;})(typeof window!=='undefined'?window:globalThis);\n`);
console.log(`Built ${rings.length} rings, ${rings.reduce((n, r) => n + r.length, 0)} vertices; ${width} x ${height}.`);
